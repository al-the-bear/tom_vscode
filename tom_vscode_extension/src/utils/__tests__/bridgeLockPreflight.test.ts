/**
 * The installers' preflight over the bridge's tom_* resolutions
 * (scripts/bridge-lock-preflight.cjs, called by install_extension.sh / .ps1).
 *
 * tom_vscode_bridge's pubspec.lock is machine-local and `dart pub get` never
 * moves it, so a host can hold a tom_* release that satisfies every declared
 * bound and lacks an API the regenerated bridges call — which failed only at
 * `dart compile exe`, after the whole build (legiondary01, tom_d4rt 1.224.0).
 *
 *   BLP-1 the lock reader keeps hosted packages with their versions; path / git / sdk entries are left out
 *   BLP-2 version order: numeric, a pre-release before its release
 *   BLP-3 the pub cache's newest release of a package: exact name, pre-releases ignored
 *   BLP-4 pub.dev's answer wins; without one the pub cache answers; with neither the package is not measured
 *         (and never counted frozen); frozen = locked older than newest
 *   BLP-5 the command: --warn names the frozen package and the upgrade command and exits 0; no lock is fine;
 *         without a mode it refuses
 *   BLP-6 the installers: from source, `--fix` runs right after the Dart SDK is found, before anything is built,
 *         and stops the install when it fails; the prebuilt route warns; PowerShell through Invoke-Native
 */

/* eslint-disable @typescript-eslint/no-require-imports, @typescript-eslint/naming-convention -- package names and env keys as pub writes them */
import test, { describe } from 'node:test';
import assert from 'node:assert/strict';
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';

// out/utils/__tests__ -> project root is three levels up.
const ROOT = join(__dirname, '..', '..', '..');
const SCRIPT = join(ROOT, 'scripts', 'bridge-lock-preflight.cjs');
const pre = require(SCRIPT);

const LOCK = `# Generated by pub
packages:
  analyzer:
    dependency: transitive
    description:
      name: analyzer
      url: "https://pub.dev"
    source: hosted
    version: "8.1.0"
  tom_d4rt:
    dependency: "direct main"
    description:
      name: tom_d4rt
      url: "https://pub.dev"
    source: hosted
    version: "1.224.0"
  tom_d4rt_ast:
    dependency: transitive
    description:
      name: tom_d4rt_ast
      url: "https://pub.dev"
    source: hosted
    version: "0.176.0"
  tom_vscode_scripting_api:
    dependency: "direct main"
    description:
      path: "../tom_vscode_scripting_api"
      relative: true
    source: path
    version: "2.0.0"
  flutter:
    dependency: "direct main"
    description: flutter
    source: sdk
    version: "0.0.0"
sdks:
  dart: ">=3.9.0 <4.0.0"
`;

describe('bridge lock preflight', () => {
    test('BLP-1: the lock reader', () => {
        assert.deepEqual(pre.parseHostedLock(LOCK), [
            { name: 'analyzer', version: '8.1.0' },
            { name: 'tom_d4rt', version: '1.224.0' },
            { name: 'tom_d4rt_ast', version: '0.176.0' },
        ]);
        assert.deepEqual(pre.parseHostedLock(LOCK.replace(/\n/g, '\r\n')).length, 3, 'CRLF (Windows)');
    });

    test('BLP-2: version order', () => {
        assert.ok(pre.compareVersions('1.224.0', '1.225.0') < 0);
        assert.ok(pre.compareVersions('1.10.0', '1.9.9') > 0, 'numeric, not text');
        assert.ok(pre.compareVersions('2.0.0-dev.1', '2.0.0') < 0);
        assert.equal(pre.compareVersions('1.0.0+3', '1.0.0'), 0);
    });

    test('BLP-3: the pub cache', () => {
        const listing = ['tom_d4rt-1.224.0', 'tom_d4rt-1.225.0', 'tom_d4rt-1.226.0-dev.1', 'tom_d4rt_ast-9.0.0', 'analyzer-8.1.0'];
        assert.equal(pre.newestInCacheListing('tom_d4rt', listing), '1.225.0');
        assert.equal(pre.newestInCacheListing('tom_d4rt_ast', listing), '9.0.0');
        assert.equal(pre.newestInCacheListing('tom_basics', listing), null);
        assert.equal(pre.pubCacheRoot({ PUB_CACHE: '/x/cache' }, 'linux'), '/x/cache');
        assert.equal(pre.pubCacheRoot({ LOCALAPPDATA: 'C:\\U\\AppData\\Local' }, 'win32'), join('C:\\U\\AppData\\Local', 'Pub', 'Cache'));
    });

    test('BLP-4: where the newest version comes from', async () => {
        const cache = mkdtempSync(join(tmpdir(), 'blp-cache-'));
        try {
            mkdirSync(join(cache, 'hosted', 'pub.dev', 'tom_d4rt_ast-0.177.0'), { recursive: true });
            const online: Record<string, string | null> = { tom_d4rt: '1.225.0', tom_d4rt_ast: null };
            const measured = await pre.measure(LOCK, { cacheRoot: cache, latest: async (n: string) => online[n] ?? null });
            assert.deepEqual(measured, [
                { name: 'tom_d4rt', locked: '1.224.0', newest: '1.225.0', source: 'pub.dev' },
                { name: 'tom_d4rt_ast', locked: '0.176.0', newest: '0.177.0', source: 'pub cache' },
            ], 'only tom_* packages; pub.dev first, the cache when pub.dev gives nothing');
            assert.deepEqual(pre.frozenOf(measured).map((m: { name: string }) => m.name), ['tom_d4rt', 'tom_d4rt_ast']);
            const offline = await pre.measure(LOCK, { cacheRoot: cache, offline: true, latest: async () => { throw new Error('asked pub.dev'); } });
            assert.equal(offline[0].source, 'unknown', 'offline and not cached: not measured');
            assert.deepEqual(pre.frozenOf(offline).map((m: { name: string }) => m.name), ['tom_d4rt_ast'], 'an unmeasured package is never frozen');
        } finally { rmSync(cache, { recursive: true, force: true }); }
    });

    test('BLP-5: the command', () => {
        const dir = mkdtempSync(join(tmpdir(), 'blp-bridge-'));
        const cache = mkdtempSync(join(tmpdir(), 'blp-cache-'));
        try {
            const run = (...args: string[]) => spawnSync(process.execPath, [SCRIPT, ...args, dir], { encoding: 'utf8', env: { ...process.env, PUB_CACHE: cache } });
            const none = run('--warn', '--offline');
            assert.equal(none.status, 0);
            assert.match(none.stdout, /no pubspec\.lock yet/);
            writeFileSync(join(dir, 'pubspec.lock'), LOCK);
            mkdirSync(join(cache, 'hosted', 'pub.dev', 'tom_d4rt-1.225.0'), { recursive: true });
            const warn = run('--warn', '--offline');
            assert.equal(warn.status, 0, warn.stderr);
            assert.match(warn.stdout, /tom_d4rt 1\.224\.0 \(newest 1\.225\.0, pub cache\)/);
            assert.match(warn.stdout, /dart pub upgrade tom_d4rt\b/);
            assert.match(warn.stdout, /not measured .*tom_d4rt_ast/);
            assert.equal(run('--offline').status, 2, 'no mode: refused');
        } finally {
            rmSync(dir, { recursive: true, force: true });
            rmSync(cache, { recursive: true, force: true });
        }
    });

    test('BLP-6: both installers', () => {
        const sh = readFileSync(join(ROOT, 'install_extension.sh'), 'utf8');
        const fixSh = sh.indexOf('node scripts/bridge-lock-preflight.cjs --fix || exit 1');
        assert.ok(fixSh > 0, '.sh: from source upgrades and stops on failure');
        assert.ok(fixSh > sh.indexOf('DART_DIR="$(node scripts/find-dart.cjs)"'), '.sh: after the Dart SDK is found');
        assert.ok(fixSh < sh.indexOf('node scripts/build-som-packages.cjs'), '.sh: before anything is built');
        assert.match(sh.slice(sh.lastIndexOf('if [ "${TOM_BRIDGE_FROM_SOURCE:-0}" = "1" ]', fixSh), fixSh), /TOM_BRIDGE_FROM_SOURCE/);
        assert.match(sh, /node scripts\/bridge-lock-preflight\.cjs --warn \) \|\| true/, '.sh: the prebuilt route warns');

        const ps = readFileSync(join(ROOT, 'install_extension.ps1'), 'utf8');
        const fixPs = ps.indexOf('Invoke-Native { node scripts/bridge-lock-preflight.cjs --fix }');
        assert.ok(fixPs > 0, '.ps1: from source, through Invoke-Native');
        assert.ok(fixPs > ps.indexOf('$DartDir = Invoke-Native { node scripts/find-dart.cjs }'));
        assert.ok(fixPs < ps.indexOf('Invoke-Native { node scripts/build-som-packages.cjs }'));
        assert.match(ps.slice(fixPs, fixPs + 200), /if \(\$LASTEXITCODE -ne 0\) \{\s*Write-Error[^\n]*\n\s*exit 1/, '.ps1: stops on failure');
        assert.match(ps, /Invoke-Native \{ node \(Join-Path \$PSScriptRoot 'scripts\/bridge-lock-preflight\.cjs'\) --warn \}/, '.ps1: the prebuilt route warns');
    });
});
