#!/usr/bin/env node
/**
 * bridge-generated-churn.cjs — after a from-source build regenerated
 * tom_vscode_bridge's d4rt bridges (`*.b.dart`), put back every file whose
 * only change is its `// Generated: <time> by tom_d4rt_generator <v>` line.
 *
 * Why: the generator stamps the time into every file it writes, so a build
 * that changed nothing still left five tracked files modified, and somebody
 * had to commit or discard that churn by hand after every build. A
 * regeneration that really changed a bridge — the scripting API grew, the
 * generator changed — stays modified and is named, so it gets committed;
 * that is the change the bridge's BRIDGE-FRESH-01 test would otherwise
 * report as stale.
 *
 * The same build also runs the versioner, which rewrites the bridge's version
 * stamp (`lib/src/version.versioner.dart`) and `tom_build_state.json` with the
 * build time, commit and a new build number. When the version itself is
 * unchanged, both are put back too: the compiled tom_bs already carries this
 * build's stamp, and the repository keeps the one of the last version bump.
 * A version bump stays, both files, to be committed.
 *
 * Usage: node scripts/bridge-generated-churn.cjs <bridge package dir>
 * Exit 0 always (a real change is reported, not an error).
 */

'use strict';

const { execFileSync } = require('child_process');
const fs = require('fs');
const path = require('path');

/** The header line the generator rewrites on every run. */
const GENERATED_LINE = /^\/\/ Generated: .* by tom_d4rt_generator\b.*$/;

function significant(text) {
    return text.replace(/\r\n/g, '\n').split('\n').filter((line) => !GENERATED_LINE.test(line)).join('\n');
}

/** Whether `after` differs from `before` in the generator's time stamp line(s) only. */
function onlyGeneratedHeaderChanged(before, after) {
    if (before.replace(/\r\n/g, '\n') === after.replace(/\r\n/g, '\n')) { return false; }
    return significant(before) === significant(after);
}

/** The versioner's lines that change on every build. */
const STAMP_LINE = /^(\/\/ Generated by versioner at |\s*static const (String buildTime|String gitCommit|int buildNumber|String dartSdkVersion) = )/;

/** Whether a versioner stamp differs only in its per-build lines (time, commit, build number, SDK). */
function onlyStampChanged(before, after) {
    const keep = (text) => text.replace(/\r\n/g, '\n').split('\n').filter((line) => !STAMP_LINE.test(line)).join('\n');
    if (before.replace(/\r\n/g, '\n') === after.replace(/\r\n/g, '\n')) { return false; }
    return keep(before) === keep(after);
}

const VERSIONER = 'lib/src/version.versioner.dart';
const BUILD_STATE = 'tom_build_state.json';

function git(cwd, args) {
    return execFileSync('git', args, { cwd, encoding: 'utf8', maxBuffer: 256 * 1024 * 1024 });
}

/** The committed text of `rel` (relative to `dir`). `./` keeps it relative to `dir`, symlinked paths included. */
function committedText(dir, rel) {
    return git(dir, ['show', `HEAD:./${rel.split(path.sep).join('/')}`]);
}

/**
 * Put back the header-only changes of the `*.b.dart` files under `dir`.
 * Answers the restored files and the ones with real changes, as paths
 * relative to `dir`.
 */
function restoreHeaderOnlyBridgeChanges(dir) {
    const changedFiles = git(dir, ['diff', '--name-only', '--relative', '--', '*.b.dart'])
        .split('\n').map((s) => s.trim()).filter(Boolean).sort();
    const restored = [];
    const changed = [];
    for (const rel of changedFiles) {
        const abs = path.join(dir, rel);
        if (!fs.existsSync(abs)) { changed.push(rel); continue; }
        const committed = committedText(dir, rel);
        if (onlyGeneratedHeaderChanged(committed, fs.readFileSync(abs, 'utf8'))) {
            fs.writeFileSync(abs, committed);
            restored.push(rel);
        } else {
            changed.push(rel);
        }
    }
    return { restored, changed };
}

/**
 * Put back the versioner stamp and the build state when only the stamp moved;
 * they go back together, so the next build counts on from the committed number.
 */
function restoreStampOnlyBuildState(dir) {
    const changed = git(dir, ['diff', '--name-only', '--relative', '--', VERSIONER, BUILD_STATE])
        .split('\n').map((s) => s.trim()).filter(Boolean).sort();
    if (!changed.includes(VERSIONER)) { return { restored: [], changed }; }
    const committed = (rel) => committedText(dir, rel);
    if (!onlyStampChanged(committed(VERSIONER), fs.readFileSync(path.join(dir, VERSIONER), 'utf8'))) {
        return { restored: [], changed };
    }
    for (const rel of changed) { fs.writeFileSync(path.join(dir, rel), committed(rel)); }
    return { restored: changed, changed: [] };
}

if (require.main === module) {
    const dir = path.resolve(process.argv[2] || '.');
    const { restored, changed } = restoreHeaderOnlyBridgeChanges(dir);
    if (restored.length) {
        console.log(`  ✔ ${restored.length} bridge file(s) unchanged apart from the generator's time stamp — kept as committed`);
    }
    if (changed.length) {
        console.log(`  ⚠️  The regeneration changed ${changed.length} bridge file(s) — commit them with the bridge:`);
        for (const f of changed) { console.log(`     ${f}`); }
    }
    if (!restored.length && !changed.length) { console.log('  ✔ bridges unchanged'); }
    const stamp = restoreStampOnlyBuildState(dir);
    if (stamp.restored.length) {
        console.log('  ✔ version stamp and build state: only this build\'s stamp moved — kept as committed (tom_bs carries the new one)');
    }
    if (stamp.changed.length) {
        console.log('  ⚠️  The version changed — commit the stamp and the build state with the bridge:');
        for (const f of stamp.changed) { console.log(`     ${f}`); }
    }
}

module.exports = { onlyGeneratedHeaderChanged, restoreHeaderOnlyBridgeChanges, onlyStampChanged, restoreStampOnlyBuildState };
